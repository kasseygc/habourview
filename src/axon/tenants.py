"""The houses (tenants) this prototype knows about.

In production the tenant comes from the signed-in session. Nothing a user types,
and nothing the LLM writes, can choose it.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from axon.config import RAW_DIR, WAREHOUSE_DIR


@dataclass(frozen=True)
class Tenant:
    id: str
    name: str
    csv_path: Path

    @property
    def warehouse_path(self) -> Path:
        return WAREHOUSE_DIR / f"{self.id}.duckdb"

    @property
    def directory_path(self) -> Path:
        """Known client and contact names, used only to redact them. In production this comes from the
        house's case-management system and never leaves it; here it is a small synthetic list."""
        return RAW_DIR / f"{self.id}_directory.csv"

    def directory(self) -> tuple[str, ...]:
        return _read_directory(self.directory_path)


@lru_cache(maxsize=8)
def _read_directory(path: Path) -> tuple[str, ...]:
    if not path.exists():
        return ()
    with path.open(newline="") as f:
        return tuple(row["name"] for row in csv.DictReader(f) if row.get("name"))


TENANTS: dict[str, Tenant] = {
    "harbourview": Tenant("harbourview", "Harbourview House", RAW_DIR / "harbourview_residents.csv"),
    # Generated by scripts/generate_data.py (synthetic, invented for testing). It is not in the brief or
    # the given data; it exists only so tests can prove one house never sees another's data.
    "testhouse": Tenant("testhouse", "Generated test house (synthetic)", RAW_DIR / "testhouse_residents.csv"),
}


def get_tenant(tenant_id: str) -> Tenant:
    try:
        return TENANTS[tenant_id]
    except KeyError:
        raise KeyError(f"Unknown tenant: {tenant_id!r}") from None
